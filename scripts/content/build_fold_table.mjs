#!/usr/bin/env node
/**
 * Generate functions/_lib/fold_table.js: the 301s for pages folded into a hub (8 Nov 2026, her yes:
 * "take away and consolidate pages"). The redirects live in data/content/manual_redirects.json
 * (entries with served_by: "edge"); Pages' static _redirects file stops at 2,000 rules and already
 * holds ~1,700, so these are answered by the edge middleware instead (functions/_lib/host_consolidation.js).
 * Every request form is listed: /x and /x.html for a file page; /x/, /x and /x/index for a folder page.
 *
 *   node scripts/content/build_fold_table.mjs           write the table
 *   node scripts/content/build_fold_table.mjs --check   exit 1 when the table and the JSON disagree
 */
import fs from 'node:fs';

const OUT = 'functions/_lib/fold_table.js';
export function foldPairs(redirects) {
  const pairs = new Map();
  for (const r of redirects.filter((e) => e.served_by === 'edge')) {
    const p = '/' + r.source_path.replace(/^\/+/, '');
    const forms = p.endsWith('/index.html') ? [p.slice(0, -10), p.slice(0, -11), p.slice(0, -5)] : [p.replace(/\.html$/, '')];
    // Targets are relative (the reference rewriter needs that); the edge answers with the product host.
    for (const f of forms) pairs.set(f, new URL(r.target, `https://${r.domain || 'billionairehighperformancecoach.com'}`).href);
  }
  return [...pairs].sort((a, b) => a[0].localeCompare(b[0]));
}
export function render(pairs) {
  return `// GENERATED by scripts/content/build_fold_table.mjs from data/content/manual_redirects.json (served_by: "edge").\n// Route key (functions/_lib/route_owner_host.js routeKeyFor) -> 301 target. ${pairs.length} keys.\nexport const FOLDED_ROUTES = new Map(${JSON.stringify(pairs)});\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const pairs = foldPairs(JSON.parse(fs.readFileSync('data/content/manual_redirects.json', 'utf8')).redirects);
  const text = render(pairs);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) { console.error(`[fold-table] FAIL: ${OUT} is out of date; run node scripts/content/build_fold_table.mjs`); process.exit(1); }
    console.log(`[fold-table] OK: ${pairs.length} keys`);
  } else { fs.writeFileSync(OUT, text); console.log(`OUTPUT [fold-table] wrote ${pairs.length} keys`); }
}
