/**
 * Generate functions/_lib/route_owner_table.js: the routes whose canonical owner
 * is billionairehighperformancecoach.com (Search Readiness checklist item a2).
 *
 * One Pages deployment answers both public hosts from one tree, so every page
 * exists at two addresses and only one of them is the canonical one. The table
 * is DERIVED, never hand-kept: it is read from the rel=canonical each page
 * actually carries, which scripts/repair/repair_dual_domain_metadata.js writes
 * from the one route-ownership definition (scripts/lib/dual_domain_policy.cjs).
 * So the edge cannot disagree with the tag, because the tag is where it came
 * from.
 *
 * Only BHPC-owned routes are listed, and the edge redirects only a route it
 * finds here. A path that is not in the table is passed through, so an unknown
 * path still answers a real 404 on the host that was asked - item a9 requires
 * exactly that, and "redirect everything not spry-owned" would have broken it.
 *
 * Run: npm run build:route-owner-table (and in build:all:uncached, after the
 * canonicals are written). Guarded by npm run validate:route-owner-host.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require_ = createRequire(import.meta.url);
const { listIndexablePages } = require_('../lib/site_pages.js');
const { routeFor } = require_('../lib/dual_domain_policy.cjs');

const ROOT = process.cwd();
const OUT = 'functions/_lib/route_owner_table.js';
const BHPC = 'billionairehighperformancecoach.com';
const SPRY = 'spryexecutiveos.com';

/** The host named by a page's rel=canonical, or '' when it names neither host. */
export function canonicalHostOf(html) {
  const m = html.match(/<link\b[^>]*rel=["']canonical["'][^>]*>/i);
  const href = m && (m[0].match(/href=["']([^"']+)["']/i) || [])[1];
  try { return new URL(href).host.toLowerCase(); } catch { return ''; }
}

/** The BHPC-owned routes, sorted, read from the committed pages' canonicals. */
export function bhpcRoutes(root = ROOT) {
  const out = new Set();
  let spry = 0;
  let other = 0;
  for (const rel of listIndexablePages(root)) {
    const host = canonicalHostOf(fs.readFileSync(path.join(root, rel), 'utf8'));
    const route = routeFor(rel);
    if (host === BHPC) out.add(route);
    else if (host === SPRY) spry += 1;
    // A canonical on neither host (a page whose canonical address lives on its
    // own domain, such as /aplayermode/) is NOT listed: that route must not be
    // redirected between the two shared hosts.
    else other += 1;
  }
  return { routes: [...out].sort(), spry, other };
}

export function render({ routes, spry, other }) {
  return `/**
 * GENERATED by scripts/build/build_route_owner_table.mjs - do not edit.
 *
 * The routes whose canonical owner is ${BHPC},
 * read from the rel=canonical each page carries. Every other published route
 * belongs to ${SPRY}; a route absent from this file is
 * passed through, never redirected, so unknown paths still 404 where they were
 * asked for.
 *
 * ${routes.length} BHPC-owned routes, ${spry} ${SPRY}-owned, ${other} canonical elsewhere.
 * Rules: functions/_lib/route_owner_host.js. Guard: npm run validate:route-owner-host.
 */
export const BHPC_HOST = '${BHPC}';
export const SPRY_HOST = '${SPRY}';

/** Newline-joined rather than an array literal: same routes, a smaller module. */
const BHPC_ROUTE_LIST = \`${routes.join('\n')}\`;

export const BHPC_ROUTES = new Set(BHPC_ROUTE_LIST.split('\\n'));
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const data = bhpcRoutes();
  if (!data.routes.length) {
    console.error('[build:route-owner-table] FAIL: 0 BHPC-owned routes found; expected the product surface.');
    process.exit(1);
  }
  const text = render(data);
  const abs = path.join(ROOT, OUT);
  const before = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : '';
  if (before !== text) fs.writeFileSync(abs, text);
  console.log(`[build:route-owner-table] ${before === text ? 'unchanged' : 'wrote'} ${OUT}: ${data.routes.length} BHPC routes, ${data.spry} spry, ${data.other} elsewhere`);
}
